def write_fixtures(fixtures_root: Path) -> None:
    inputs = fixtures_root / "inputs"
    quality = fixtures_root / "quality"
    inputs.mkdir(parents=True, exist_ok=True)
    quality.mkdir(parents=True, exist_ok=True)
    for name, text in sorted(CASES.items()):
        (inputs / name).write_bytes(text.encode("utf-8"))
        print(f"wrote {name} ({len(text.encode('utf-8'))} bytes)")
    manifest = quality / "manifest.json"
    manifest.write_text(
        json.dumps(QUALITY_MANIFEST, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {manifest.relative_to(fixtures_root)}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--root",
        type=Path,
        default=DEFAULT_FIXTURES_ROOT,
        help="fixture output root (default: repository fixtures/)",
    )
    args = parser.parse_args()
    write_fixtures(args.root.resolve())


if __name__ == "__main__":
    main()
